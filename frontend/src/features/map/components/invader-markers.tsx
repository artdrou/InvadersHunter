// Default state silhouettes (DEFAULT_SHAPE_FOR_STATE): destroyed → ghost, not
// visible → same sprite as its tier. In State mode a destroyed invader is always
// "state-destroyed" (other state colors never meet the -destroyed suffix), so the
// remaining combinations just get a valid image.
export const BUNDLED_MARKER_IMAGES: Record<string, ImageSourcePropType> = { ...TIER_MARKER_IMAGES };
for (const tier of TIER_VALUES) {
  for (const display of MARKER_DISPLAYS) {
    const ghost = display === 'rarity'
      ? DESTROYED_RARITY_IMAGES[tier]
      : DESTROYED_IMAGES[display] ?? markerDestroyedStateDestroyed;
    BUNDLED_MARKER_IMAGES[markerKey(tier, display)] ??= ghost;
    BUNDLED_MARKER_IMAGES[markerKey(tier, display, 'destroyed')] = ghost;
    BUNDLED_MARKER_IMAGES[markerKey(tier, display, 'notVisible')] = BUNDLED_MARKER_IMAGES[markerKey(tier, display)];
  }
}

// Merges the bundled default sprites with any user-generated marker PNGs
// (@/features/settings/marker-customization-store) — custom entries override
// bundled ones key-for-key, so uncustomized states keep shipping visuals.
export function useMarkerImages(): Record<string, ImageSourcePropType | number> {
  const customIconUris = useMarkerCustomizationStore((s) => s.customIconUris);
  return useMemo(() => {
    if (!customIconUris) return BUNDLED_MARKER_IMAGES;
    const merged: Record<string, ImageSourcePropType | number> = { ...BUNDLED_MARKER_IMAGES };
    for (const [key, uri] of Object.entries(customIconUris)) merged[key] = { uri };
    return merged;
  }, [customIconUris]);
}

// MapLibre's native <Images> only ever registers a given key once and
// ignores later value updates for it (confirmed in both the Android and iOS
// implementations of @maplibre/maplibre-react-native) — so after a
// re-customization the merged map from useMarkerImages() above is useless to
// an already-mounted map unless the whole component remounts. WebMap.native.tsx
// keys <Images> on this value to force that remount whenever it changes.
export function useMarkerImagesVersion(): number {
  return useMarkerCustomizationStore((s) => s.generationVersion);
}

export function useMarkerLayerStyle(): SymbolLayerStyle {
  const opacity = useMarkerCustomizationStore((s) => s.opacity);
  return useMemo(() => ({
    iconImage: ["get", "iconKey"] as Expression,
    iconSize: ["get", "iconSize"] as Expression,
    // Each customizable state carries its own opacity (set on the customization
    // screen). Order mirrors resolveIconKey's precedence: a highlighted marker
    // wins over everything, pending stays a fixed sync-in-progress dim, then
    // grey-mode, then captured vs uncaptured. Defaults (grey 0.8, the rest 1)
    // reproduce the old fixed 0.8 / 1.0 look until the user changes anything.
    iconOpacity: ["case",
      ["==", ["get", "highlight"], 1], opacity.highlight,
      ["==", ["get", "pending"], 1],   0.45,
      ["==", ["get", "grey"], 1],      opacity.grey,
      ["==", ["get", "captured"], 1],  opacity.flashCaptured,
      opacity.flashUncaptured,
    ] as Expression,
    iconAllowOverlap: true,
    iconIgnorePlacement: true,
  }), [opacity]);
}

