"""
Profile icon shapes: clean up hand-drawn pixel-art SVGs and register them in the app.

    python normalize_avatars.py path/to/raw.svg:small-4 [more.svg:big-3 ...]

For each raw SVG (10x10 <rect> cells):
  - crops to the drawn pixels and centres them on a CANVAS x CANVAS square
  - maps its greys onto the shared palette, by role (the app recolours by luminance
    rank, so only the order matters in-app — this keeps the sources consistent):
      eyes (darker, <= 2 cells) #121212 · shade (darker) #4f4f4f · body #808080
      light (any lighter grey: eye whites, wing interiors…) #ffffff
  - writes src/avatars/avatar-<id>.svg

Then (always) regenerates frontend/src/features/marker-customization/extra-shapes.ts from
src/avatars/: extra silhouettes offered for both the profile icon and the map markers.
The 6 default marker shapes (src/shape-*.svg) are not touched.
"""
import re
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).parent
AVATAR_DIR = HERE / "src" / "avatars"
TS_OUT = HERE.parent.parent / "frontend" / "src" / "features" / "marker-customization" / "extra-shapes.ts"
CANVAS = 200  # same as the largest marker shape; the app rasterizes at 256, so it must stay below
CELL = 10
SIZE_ORDER = {"small": 0, "medium": 1, "big": 2}

EYE, SHADE, BODY, LIGHT = "#121212", "#4f4f4f", "#808080", "#ffffff"
RECT = re.compile(r'<rect x="(\d+)" y="(\d+)" width="(\d+)" height="(\d+)" fill="(#[0-9a-fA-F]{6})"\s*/>')


def lum(hex_color: str) -> float:
    r, g, b = (int(hex_color[i:i + 2], 16) for i in (1, 3, 5))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def palette_map(counts: Counter) -> dict:
    """Source grey → shared palette grey, keeping the luminance order."""
    total = sum(counts.values())
    # Body: the lightest colour covering >= 25% of the cells (big outlined invaders
    # have more shade cells than body cells)
    body = max((c for c, n in counts.items() if n / total >= 0.25), key=lum)
    darker = sorted((c for c in counts if lum(c) < lum(body)), key=lum)
    lighter = sorted((c for c in counts if lum(c) > lum(body)), key=lum)
    if len(darker) > 2:
        raise ValueError(f"too many shades: {sorted(counts, key=lum)}")

    out = {body: BODY}
    if len(darker) == 2:
        out[darker[0]], out[darker[1]] = EYE, SHADE
    elif darker:
        out[darker[0]] = EYE if counts[darker[0]] <= 2 else SHADE
    # Every lighter grey reads as the same white once colored (bat wings = eye whites)
    for c in lighter:
        out[c] = LIGHT
    return out


def normalize(svg: str) -> str:
    cells = [(int(x), int(y), fill.lower()) for x, y, w, h, fill in RECT.findall(svg)
             if (w, h) == (str(CELL), str(CELL))]
    if not cells or len(cells) != len(RECT.findall(svg)):
        raise ValueError("expected only 10x10 <rect> cells")
    colors = palette_map(Counter(f for _, _, f in cells))

    min_x, min_y = min(x for x, _, _ in cells), min(y for _, y, _ in cells)
    w = max(x for x, _, _ in cells) + CELL - min_x
    h = max(y for _, y, _ in cells) + CELL - min_y
    if max(w, h) > CANVAS:
        raise ValueError(f"{w}x{h} does not fit {CANVAS}x{CANVAS}")
    # Exact centre (a half-cell offset when the free space is an odd number of cells)
    dx, dy = (CANVAS - w) / 2 - min_x, (CANVAS - h) / 2 - min_y
    num = lambda v: str(int(v)) if v == int(v) else str(v)

    lines = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {CANVAS} {CANVAS}" '
             f'width="{CANVAS}" height="{CANVAS}" shape-rendering="crispEdges">']
    for x, y, fill in sorted(cells, key=lambda c: (c[1], c[0])):
        lines.append(f'  <rect x="{num(x + dx)}" y="{num(y + dy)}" width="{CELL}" height="{CELL}" fill="{colors[fill]}"/>')
    lines.append("</svg>")
    return "\n".join(lines) + "\n"


def sort_key(shape_id: str):
    size, _, n = shape_id.partition("-")
    return (SIZE_ORDER.get(size, 9), size, int(n) if n.isdigit() else 0)


def emit_ts() -> None:
    files = sorted(AVATAR_DIR.glob("avatar-*.svg"), key=lambda p: sort_key(p.stem[len("avatar-"):]))
    ids = [p.stem[len("avatar-"):] for p in files]
    body = "\n".join(f"  '{i}': `{p.read_text(encoding='utf-8').strip()}`," for i, p in zip(ids, files))
    TS_OUT.write_text(
        "// GENERATED by dev/markers/normalize_avatars.py from dev/markers/src/avatars/ — do not edit.\n"
        "// Extra silhouettes, offered after the 6 tier shapes for the profile icon and the map markers.\n\n"
        f"export const EXTRA_SHAPE_IDS = [{', '.join(repr(i) for i in ids)}] as const;\n\n"
        "export type ExtraShapeId = (typeof EXTRA_SHAPE_IDS)[number];\n\n"
        f"export const EXTRA_SHAPE_SVG: Record<ExtraShapeId, string> = {{\n{body}\n}};\n",
        encoding="utf-8", newline="\n",
    )
    print(f"{TS_OUT.relative_to(HERE.parent.parent)}: {len(ids)} shapes ({', '.join(ids)})")


def main(args: list) -> None:
    AVATAR_DIR.mkdir(parents=True, exist_ok=True)
    for arg in args:
        src, _, shape_id = arg.rpartition(":")
        if not src or not re.fullmatch(r"[a-z]+-\d+", shape_id):
            sys.exit(f"usage: normalize_avatars.py raw.svg:<size>-<n> ...  (got {arg!r})")
        out = AVATAR_DIR / f"avatar-{shape_id}.svg"
        out.write_text(normalize(Path(src).read_text(encoding="utf-8")), encoding="utf-8", newline="\n")
        print(f"{src} -> {out.relative_to(HERE)}")
    emit_ts()


if __name__ == "__main__":
    main(sys.argv[1:])
