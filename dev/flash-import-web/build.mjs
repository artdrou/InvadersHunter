// Bundles src/phone.js (+ Tango ADB) into a single ES module served by the backend.
// Run after changing src/ or bumping the @yume-chan packages:
//   npm install && npm run build
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const out = fileURLToPath(new URL('../../backend/static/flash_import/web/phone.js', import.meta.url));

await build({
  entryPoints: ['src/phone.js'],
  bundle: true,
  format: 'esm',
  target: 'chrome110',
  minify: true,
  legalComments: 'eof',
  outfile: out,
  banner: { js: '// Generated by dev/flash-import-web (npm run build). Do not edit.' },
});
console.log(`-> ${out}`);
